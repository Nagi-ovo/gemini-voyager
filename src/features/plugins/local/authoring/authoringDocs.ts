/**
 * The two documents a coding agent reads, rendered from the plugin contract:
 * - the public `SKILL.md` (every site; `bun run skills:build` writes it to
 *   `docs/public/skills/write-voyager-plugin/SKILL.md`), and
 * - the `AGENTS.md` that `create-voyager-plugin init` writes into a plugin
 *   folder (one site).
 * Both take the sites explicitly so the CLI, which has no Vite glob, renders
 * exactly what the extension build would.
 */
import type { SiteAdapter } from '../../types';
import { authoringWorkflowSection } from './authoringWorkflow';
import type { ContractSection } from './contractRules';
import { buildPluginContract, renderExample, renderSections, siteSection } from './pluginContract';
import { isUnrestrictedSite } from './siteFacts';
import { WRITE_PLUGIN_SKILL_NAME, WRITE_PLUGIN_SKILL_URL } from './skillLink';

const INTRO = [
  'Voyager is a browser extension for AI chat sites. A local plugin is a declarative JSON manifest (plugin.json) plus CSS that restyles or rearranges a chat page through reversible page changes. It runs no code of its own: Voyager checks it strictly on import, applies it, and removes every change when the plugin is turned off.',
];

/** Where the plugin may run: the site the reference sections were written for. */
function referenceSite(sites: readonly SiteAdapter[]): SiteAdapter {
  const site = sites.find(isUnrestrictedSite) ?? sites[0];
  if (!site) throw new Error('no site adapters to render the plugin contract from');
  return site;
}

function withoutSiteSection(sections: readonly ContractSection[]): ContractSection[] {
  return sections.filter((section) => !section.title.startsWith('Target site: '));
}

/** The public skill: shared rules once, then the facts of every site. */
export function renderWriteVoyagerPluginSkill(sites: readonly SiteAdapter[]): string {
  const reference = buildPluginContract(referenceSite(sites), { audience: 'agent' });
  const siteIds = sites.map((site) => site.id).join(', ');
  return [
    '---',
    `name: ${WRITE_PLUGIN_SKILL_NAME}`,
    `description: ${JSON.stringify(`Write and check a local plugin for the Voyager browser extension (${sites.map((site) => site.label).join(', ')}). A plugin is a JSON manifest plus CSS that restyles or rearranges the chat page. Use when the user wants to change how one of these sites looks or is laid out through Voyager.`)}`,
    '---',
    '',
    '# Write a Voyager plugin',
    '',
    ...INTRO,
    '',
    `This skill is generated from Voyager’s plugin engine ${reference.engineVersion}. The latest copy is at ${WRITE_PLUGIN_SKILL_URL}.`,
    '',
    ...renderSections([authoringWorkflowSection({ scaffolded: false, siteIds })]),
    ...renderSections(withoutSiteSection(reference.sections)),
    '## Sites',
    '',
    `\`--site\` takes one of: ${siteIds}.`,
    '',
    ...renderSections(
      sites.map((site) => siteSection(site, 'agent')),
      3,
    ),
    `## Examples (for ${reference.site.label}; on another site use its "matches" and anchors)`,
    '',
    ...reference.examples.flatMap((example) => renderExample(example)),
  ].join('\n');
}

/** The AGENTS.md of a scaffolded plugin folder for one site. */
export function renderScaffoldAgents(site: SiteAdapter): string {
  const contract = buildPluginContract(site, { audience: 'agent' });
  return [
    `# Voyager plugin for ${site.label}`,
    '',
    ...INTRO,
    '',
    `Generated by create-voyager-plugin for plugin engine ${contract.engineVersion}. The full skill, covering every site, is at ${WRITE_PLUGIN_SKILL_URL}.`,
    '',
    ...renderSections([authoringWorkflowSection({ scaffolded: true, siteIds: site.id })]),
    ...renderSections(contract.sections),
    '## Examples',
    '',
    ...contract.examples.flatMap((example) => renderExample(example)),
  ].join('\n');
}
